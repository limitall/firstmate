$script:FmBriefSecondmateTemplate = @'
You are a persistent second mate managed by the main firstmate. Work on your own; do not wait for a human.

# Charter
__FM_CHARTER__

# Routing scope
__FM_SCOPE__

# Project clones
__FM_PROJECTS__

# Operating model
