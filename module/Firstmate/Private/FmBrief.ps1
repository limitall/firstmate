# Port of fm-brief.sh's shell_quote: single-quote a path for the `echo ... >>`
# line the brief tells the worker to run.
function ConvertTo-FmBriefQuotedPath {
    [CmdletBinding()]
    param([Parameter(Mandatory)][AllowEmptyString()][string]$Path)
    return "'" + $Path.Replace("'", "'\''") + "'"
}

function Expand-FmBriefTemplate {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Template,
        [Parameter(Mandatory)][hashtable]$Values
    )
    $text = $Template
    foreach ($key in $Values.Keys) {
        $text = $text.Replace($key, [string]$Values[$key])
    }
    return $text
}

