# Setup step 2 and Rule 1, per delivery mode.
function Get-FmBriefModeSections {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Mode,
        [Parameter(Mandatory)][string]$Id
    )
    switch ($Mode) {
        'direct-PR' {
            return [pscustomobject]@{
                Setup2 = ''
                Rule1  = "1. Never push to the default branch (push only your ``fm/$Id`` branch). Never merge a PR."
                Dod    = $script:FmBriefDodDirectPr
            }
        }
        'local-only' {
            return [pscustomobject]@{
                Setup2 = ''
                Rule1  = "1. Never push to any remote and never open a PR. Work only on your ``fm/$Id`` branch; firstmate handles the merge into local ``main``."
                Dod    = $script:FmBriefDodLocalOnly
            }
        }
        default {
            return [pscustomobject]@{
                Setup2 = "`n2. Run ``no-mistakes doctor``; if it reports the repo is not initialized here, run ``no-mistakes init``."
                Rule1  = '1. Never push to the default branch. Never merge a PR.'
                Dod    = $script:FmBriefDodNoMistakes
            }
        }
    }
}
