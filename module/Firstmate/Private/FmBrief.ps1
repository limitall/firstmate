# FmBrief.ps1 - the generated brief text, ported from bin/fm-brief.sh.
#
# The scaffold is a SAFETY CONTRACT, not a suggestion (AGENTS.md section 11).
# Two generated sections in particular must survive verbatim:
#   * the worktree-isolation assertion every ship brief opens its Setup with -
#     a crewmate that cannot prove it is outside the primary checkout stops
#     instead of branching and committing there;
#   * the Herdr lifecycle declaration, which is a hard gate: this scaffold
#     cannot inspect the task text that replaces {TASK} later, so a brief
#     written without --herdr-lab carries a loud declaration rather than
#     silently omitting the isolation contract.
# The status protocol, the keyed open-and-resolved semantics, and the
# delivery-mode definitions of done are equally part of the contract.
#
# Every template below is a literal block with __FM_*__ placeholders, so the
# generated bytes match bin/fm-brief.sh exactly - a brief written by a Linux
# firstmate and one written here are the same file. tests/fixtures/brief/ holds
# the bash originals the test suite diffs against.

